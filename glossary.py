def yandex_translate_glossary_pairs() -> list[dict]:
    """Формирует glossaryPairs для Yandex Translate API (glossaryConfig) из
    CANONICAL_NAMES — по одной паре на каждый вариант написания в source.

    Используется в translate_yandex_translate_api() (bot.py). Не путать с
    GLOSSARY/glossary_for_prompt() — тот список работает уже ПОСЛЕ перевода,
    через edit_gemini(), и в основном содержит RU→RU-исправления, для которых
    у glossaryConfig просто нет соответствующего исходного текста.
    """
    pairs = []
    for entry in CANONICAL_NAMES:
        ru = str(entry.get("ru", "")).strip()
        if not ru:
            continue
        for source in entry.get("source", []):
            source = str(source).strip()
            if not source:
                continue
            pairs.append({
                "sourceText": source,
                "translatedText": ru,
                "exact": bool(entry.get("exact", False)),
            })
    return pairs


def glossary_for_prompt() -> str:
    """Возвращает словарь в виде строки для вставки в промпт ИИ."""
    lines = []
    for entry in GLOSSARY:
        bad = entry["bad"]
        good = entry["good"]
        comment = entry.get("comment", "")
        if bad == good:
            continue  # пропускаем «верно» записи
        line = f'  • Неверно: «{bad}» → Верно: «{good}»'
        if comment:
            line += f"  ({comment})"
        lines.append(line)
    return "\n".join(lines)
