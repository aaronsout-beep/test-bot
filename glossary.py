# ── Защищённые имена для Yandex Translate (glossaryConfig) ──────────────────
#
# Отдельный список — НЕ для edit_gemini()/AI-редактуры (там работает GLOSSARY
# выше), а для передачи в glossaryConfig при вызове Yandex Translate API
# (translate_yandex_translate_api() в bot.py). Здесь source — форма ИЗ
# ИСХОДНОГО (нерусского) текста, а не опечатка в уже переведённом русском.
#
# Задача: не дать Yandex Translate перевести имя дословно как словарное слово
# исходного языка. Пример: турецкая фамилия "Güler" переводится как "смеётся"
# (дословно), "Yıldız" — как "звезда". NMT не распознаёт такие слова как
# фамилии без подсказки.
#
# ВАЖНО: это только "мягкая" подсказка конкретно для glossaryConfig Yandex
# Translate (exact:false, не гарантирует полную замену на короткой
# малоконтекстной строке). Раньше эти же имена ДОПОЛНИТЕЛЬНО защищались через
# отдельную жёсткую маску текста (@@NM<n>@@) перед отправкой в ЛЮБОЙ
# переводчик — но у неё была своя цена: подставленное русское имя теряло
# грамматическую связь с предложением и требовало отдельной эвристики/AI-шага
# для повторного склонения. Маска убрана: модель сама переводит и сама
